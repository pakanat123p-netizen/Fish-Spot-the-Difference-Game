// ==================== AUDIO SYSTEM (SFX & SOUNDTRACK BGM) ====================
class SoundManager {
  constructor() {
    this.ctx = null;
    this.masterGain = null;
    this.bgmGain = null;
    this.sfxGain = null;
    this.isMuted = false;
    this.bgmPlaying = false;
    this.bgmTimer = null;
    this.bgmStep = 0;
    try {
      this.isMuted = localStorage.getItem('thaiFishSoundMuted') === 'true';
    } catch(e) {}
  }

  init() {
    if (this.ctx) return;
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextClass) return;
    this.ctx = new AudioContextClass();

    this.masterGain = this.ctx.createGain();
    this.masterGain.gain.value = this.isMuted ? 0 : 1.0;
    this.masterGain.connect(this.ctx.destination);

    this.bgmGain = this.ctx.createGain();
    this.bgmGain.gain.value = 0.24; // Soft pleasant background music volume
    this.bgmGain.connect(this.masterGain);

    this.sfxGain = this.ctx.createGain();
    this.sfxGain.gain.value = 0.38; // Crisp sound effect volume
    this.sfxGain.connect(this.masterGain);

    this.updateButtons();
  }

  ensureContext() {
    this.init();
    if (this.ctx && this.ctx.state === 'suspended') {
      this.ctx.resume();
    }
  }

  toggleMute() {
    this.ensureContext();
    this.isMuted = !this.isMuted;
    try {
      localStorage.setItem('thaiFishSoundMuted', this.isMuted ? 'true' : 'false');
    } catch(e) {}

    if (this.masterGain && this.ctx) {
      this.masterGain.gain.setTargetAtTime(this.isMuted ? 0 : 1.0, this.ctx.currentTime, 0.05);
    }
    this.updateButtons();
    if (!this.isMuted && !this.bgmPlaying) {
      this.startBGM();
    }
    return !this.isMuted;
  }

  updateButtons() {
    const soundToggle = $('btn-sound-toggle');
    if (soundToggle) {
      soundToggle.textContent = this.isMuted ? '🔇' : '🔊';
      soundToggle.classList.toggle('muted', this.isMuted);
      soundToggle.title = this.isMuted ? 'เปิดเสียงและเพลง' : 'ปิดเสียงและเพลง';
    }
    const splashIcon = $('sound-splash-icon');
    const splashText = $('sound-splash-text');
    const splashBtn = $('btn-sound-splash');
    if (splashIcon) splashIcon.textContent = this.isMuted ? '🔇' : '🔊';
    if (splashText) splashText.textContent = this.isMuted ? 'ดนตรี & เสียงเอฟเฟกต์: ปิด' : 'ดนตรี & เสียงเอฟเฟกต์: เปิด';
    if (splashBtn) splashBtn.classList.toggle('muted', this.isMuted);
  }

  // 1. Click button (Crisp water bubble tap)
  playClick() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(560, t);
    osc.frequency.exponentialRampToValueAtTime(260, t + 0.06);

    gain.gain.setValueAtTime(0.22, t);
    gain.gain.exponentialRampToValueAtTime(0.001, t + 0.06);

    osc.connect(gain);
    gain.connect(this.sfxGain);

    osc.start(t);
    osc.stop(t + 0.07);
  }

  // 2. Correct spot found (Joyful 4-note major chime + sparkle)
  playCorrect() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const notes = [523.25, 659.25, 783.99, 1046.50]; // C5, E5, G5, C6
    notes.forEach((freq, i) => {
      const start = t + i * 0.055;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'triangle';
      osc.frequency.setValueAtTime(freq, start);

      gain.gain.setValueAtTime(0, start);
      gain.gain.linearRampToValueAtTime(0.32, start + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.001, start + 0.38);

      osc.connect(gain);
      gain.connect(this.sfxGain);

      osc.start(start);
      osc.stop(start + 0.40);
    });
  }

  // 3. Wrong click (Playful comical thud)
  playWrong() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'triangle';
    osc.frequency.setValueAtTime(175, t);
    osc.frequency.exponentialRampToValueAtTime(75, t + 0.16);

    gain.gain.setValueAtTime(0.26, t);
    gain.gain.exponentialRampToValueAtTime(0.001, t + 0.18);

    osc.connect(gain);
    gain.connect(this.sfxGain);

    osc.start(t);
    osc.stop(t + 0.20);
  }

  // 4. Hint sound (Mystical sonar shimmer)
  playHint() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const freqs = [440, 554.37, 659.25, 880, 1108.73];
    freqs.forEach((freq, i) => {
      const start = t + i * 0.05;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(freq, start);

      gain.gain.setValueAtTime(0.18, start);
      gain.gain.exponentialRampToValueAtTime(0.001, start + 0.32);

      osc.connect(gain);
      gain.connect(this.sfxGain);

      osc.start(start);
      osc.stop(start + 0.35);
    });
  }

  // 5. Level complete fanfare
  playLevelWin() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const chord = [392.00, 523.25, 659.25, 783.99, 1046.50];
    chord.forEach((freq, i) => {
      const start = t + i * 0.07;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'triangle';
      osc.frequency.setValueAtTime(freq, start);

      gain.gain.setValueAtTime(0, start);
      gain.gain.linearRampToValueAtTime(0.30, start + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.001, start + 0.75);

      osc.connect(gain);
      gain.connect(this.sfxGain);

      osc.start(start);
      osc.stop(start + 0.80);
    });
  }

  // 6. Time urgent tick
  playTick() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(880, t);

    gain.gain.setValueAtTime(0.14, t);
    gain.gain.exponentialRampToValueAtTime(0.001, t + 0.04);

    osc.connect(gain);
    gain.connect(this.sfxGain);

    osc.start(t);
    osc.stop(t + 0.05);
  }

  // 7. Victory fanfare
  playVictory() {
    if (this.isMuted) return;
    this.ensureContext();
    if (!this.ctx) return;

    const t = this.ctx.currentTime;
    const victoryMelody = [
      { f: 523.25, d: 0.18 }, // C5
      { f: 659.25, d: 0.18 }, // E5
      { f: 783.99, d: 0.18 }, // G5
      { f: 1046.5, d: 0.40 }, // C6
      { f: 880.00, d: 0.22 }, // A5
      { f: 1046.5, d: 0.65 }  // C6 grand
    ];
    let offset = 0;
    victoryMelody.forEach(({ f, d }) => {
      const start = t + offset;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'triangle';
      osc.frequency.setValueAtTime(f, start);

      gain.gain.setValueAtTime(0, start);
      gain.gain.linearRampToValueAtTime(0.35, start + 0.03);
      gain.gain.exponentialRampToValueAtTime(0.001, start + d);

      osc.connect(gain);
      gain.connect(this.sfxGain);

      osc.start(start);
      osc.stop(start + d + 0.05);

      offset += d * 0.82;
    });
  }

  // ===== PROCEDURAL AQUATIC SOUNDTRACK (BGM) =====
  startBGM() {
    if (this.bgmPlaying) return;
    this.ensureContext();
    if (!this.ctx) return;
    this.bgmPlaying = true;
    this.scheduleBGM();
  }

  stopBGM() {
    this.bgmPlaying = false;
    if (this.bgmTimer) {
      clearTimeout(this.bgmTimer);
      this.bgmTimer = null;
    }
  }

  scheduleBGM() {
    if (!this.bgmPlaying || !this.ctx) return;

    // Peaceful pentatonic underwater notes (C major pentatonic)
    const melody = [
      // Bar 1
      { note: 261.63, len: 0.35 }, // C4
      { note: 329.63, len: 0.35 }, // E4
      { note: 392.00, len: 0.45 }, // G4
      { note: 440.00, len: 0.35 }, // A4
      // Bar 2
      { note: 523.25, len: 0.50 }, // C5
      { note: 392.00, len: 0.35 }, // G4
      { note: 329.63, len: 0.60 }, // E4
      { note: null,   len: 0.30 }, // Rest
      // Bar 3
      { note: 293.66, len: 0.35 }, // D4
      { note: 392.00, len: 0.35 }, // G4
      { note: 440.00, len: 0.45 }, // A4
      { note: 523.25, len: 0.40 }, // C5
      // Bar 4
      { note: 440.00, len: 0.45 }, // A4
      { note: 392.00, len: 0.45 }, // G4
      { note: 261.63, len: 0.80 }, // C4 long
      { note: null,   len: 0.40 }  // Rest
    ];

    const bassLines = [130.81, 110.00, 87.31, 98.00]; // C3, A2, F2, G2
    const currentItem = melody[this.bgmStep % melody.length];
    const barIdx = Math.floor((this.bgmStep % melody.length) / 4);
    const t = this.ctx.currentTime;

    // Play melody note with warm lowpass aquatic feel
    if (currentItem.note) {
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();
      const filter = this.ctx.createBiquadFilter();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(currentItem.note, t);

      filter.type = 'lowpass';
      filter.frequency.setValueAtTime(950, t);
      filter.Q.value = 1.6;

      gain.gain.setValueAtTime(0, t);
      gain.gain.linearRampToValueAtTime(0.18, t + 0.04);
      gain.gain.exponentialRampToValueAtTime(0.001, t + currentItem.len);

      osc.connect(filter);
      filter.connect(gain);
      gain.connect(this.bgmGain);

      osc.start(t);
      osc.stop(t + currentItem.len + 0.05);

      // Bubble harmonic pop
      if (Math.random() > 0.45) {
        const bubbleOsc = this.ctx.createOscillator();
        const bubbleGain = this.ctx.createGain();
        bubbleOsc.type = 'sine';
        bubbleOsc.frequency.setValueAtTime(currentItem.note * 2, t + 0.03);
        bubbleGain.gain.setValueAtTime(0.035, t + 0.03);
        bubbleGain.gain.exponentialRampToValueAtTime(0.0001, t + 0.18);
        bubbleOsc.connect(bubbleGain);
        bubbleGain.connect(this.bgmGain);
        bubbleOsc.start(t + 0.03);
        bubbleOsc.stop(t + 0.20);
      }
    }

    // Play warm bass note at start of 4-step bar
    if (this.bgmStep % 4 === 0) {
      const bassFreq = bassLines[barIdx % bassLines.length];
      const bassOsc = this.ctx.createOscillator();
      const bassGain = this.ctx.createGain();
      bassOsc.type = 'triangle';
      bassOsc.frequency.setValueAtTime(bassFreq, t);

      bassGain.gain.setValueAtTime(0, t);
      bassGain.gain.linearRampToValueAtTime(0.20, t + 0.08);
      bassGain.gain.exponentialRampToValueAtTime(0.001, t + 1.5);

      bassOsc.connect(bassGain);
      bassGain.connect(this.bgmGain);

      bassOsc.start(t);
      bassOsc.stop(t + 1.6);
    }

    this.bgmStep++;
    const stepDuration = Math.round(currentItem.len * 1000 + 40);
    this.bgmTimer = setTimeout(() => this.scheduleBGM(), stepDuration);
  }
}


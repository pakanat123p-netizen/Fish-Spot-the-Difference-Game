  let horiz = '';
  if (diff.rx < 0.28) horiz = 'ส่วนหัว / ด้านหน้า (ฝั่งซ้าย)';
  else if (diff.rx > 0.65) horiz = 'ส่วนหาง (ฝั่งขวา)';

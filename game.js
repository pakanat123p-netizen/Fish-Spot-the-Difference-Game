// ==================== TIMER ====================
function startTimer() {
  clearInterval(state.timerInterval);
  const maxTime = DIFF_TIMES[state.difficulty] || 60;
  state.timer = maxTime;
  state.levelStartTime = Date.now();
  updateTimerDisplay();
  state.timerInterval = setInterval(() => {
    state.timer--;
    updateTimerDisplay();
    if (state.timer <= 10 && state.timer > 0) {
      sound.playTick();
    }
    if (state.timer <= 0) {
      clearInterval(state.timerInterval);
      state.timerInterval = null;
      timeUp();
    }
  }, 1000);
}
function updateTimerDisplay() {
  $('timer-val').textContent = state.timer;
  $('timer-display').classList.toggle('urgent', state.timer <= 15);
}
function stopTimer() {
  clearInterval(state.timerInterval);
  state.timerInterval = null;
  state.levelElapsed = Math.round((Date.now() - state.levelStartTime) / 1000);
}
function timeUp() {
  state.levelElapsed = DIFF_TIMES[state.difficulty] || 60;
  levelComplete(true);
}


function flashHintHighlight(hintIdx) {
  let flashes = 0;
  const iv = setInterval(() => {
    renderCanvases();
    if (flashes % 2 === 0) {
      const diff = state.activeDiffs[hintIdx];
      const layout = state.imgLayout;
      if (layout) {
        ['canvas-left', 'canvas-right'].forEach(canvasId => {
          const c = $(canvasId);
          if (!c) return;
          const ctx = c.getContext('2d');
          const cx = layout.dx + (diff.rx + diff.rw / 2) * layout.dw;
          const cy = layout.dy + (diff.ry + diff.rh / 2) * layout.dh;
          const rx = Math.max((diff.rw * layout.dw) / 2 + 14, 30);
          const ry = Math.max((diff.rh * layout.dh) / 2 + 14, 30);

          ctx.save();
          ctx.beginPath();
          ctx.ellipse(cx, cy, rx, ry, 0, 0, Math.PI * 2);
          ctx.fillStyle = 'rgba(249, 199, 79, 0.32)';
          ctx.fill();
          ctx.strokeStyle = '#ffd166';
          ctx.lineWidth = 3.5;
          ctx.setLineDash([8, 4]);
          ctx.shadowColor = '#f9c74f';
          ctx.shadowBlur = 16;
          ctx.stroke();
          ctx.restore();
        });
      }
    }
    flashes++;
    if (flashes >= 8) {
      clearInterval(iv);
      renderCanvases();
    }
  }, 260);
}

